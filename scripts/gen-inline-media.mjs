// Regenerate src/lib/inline-media.ts: compact webp data URIs for the critical
// above-the-fold images so they arrive INSIDE the HTML/JS and can't be dropped
// as separate requests on flaky / roaming / data-saver mobile connections.
// Each image is re-encoded to its actual display size so the inline payload
// stays small.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import sharp from 'sharp';

async function uri(path, { width, height, quality = 82 } = {}) {
  let img = sharp(readFileSync('public' + path), { density: 220 }); // density helps SVG raster
  if (width || height) img = img.resize({ width, height, fit: 'inside', withoutEnlargement: true });
  const buf = await img.webp({ quality, effort: 5 }).toBuffer();
  return `data:image/webp;base64,${buf.toString('base64')}`;
}

const schools = {};
for (const f of readdirSync('public/schools'))
  schools['/schools/' + f] = await uri('/schools/' + f, { height: 160, quality: 86 });

const portrait = await uri('/jb-portrait.jpg', { width: 760, quality: 80 });
const poster = await uri('/videos/hero-home-poster.jpg', { width: 1280, quality: 62 });

const out = `// AUTO-GENERATED by scripts/gen-inline-media.mjs — do not edit by hand.
// Compact webp data URIs so critical images render with the HTML and survive
// flaky / roaming / data-saver mobile networks (separate image requests were
// being dropped by carrier proxies).
export const PORTRAIT_DATA_URI = ${JSON.stringify(portrait)};
export const HERO_POSTER_DATA_URI = ${JSON.stringify(poster)};
export const SCHOOL_LOGO_DATA_URIS: Record<string, string> = ${JSON.stringify(schools, null, 1)};
`;
writeFileSync('src/lib/inline-media.ts', out);
const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0);
console.log('wrote inline-media.ts', kb(out) + 'KB total |',
  'portrait', kb(portrait) + 'KB | poster', kb(poster) + 'KB | logos', Object.keys(schools).length);
